"""Map every function in decompiled/main_dol.c: callers, callees, strings, asserts, subsystem hints.

Read-only analysis of the C export. Nothing here is a name: results are behaviour notes for
choosing what to study next, written to
  symbols/game_map.tsv   one row per function (addr, name, lines, callers, callees, hints, strings)
  docs/game_map.md       summary: subsystems, source-file runs, hub functions, file-name users
usage: python -I tools/game_map.py
"""
import collections, os, re

G = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME_END = 0x80131000  # first SDK function (dtk) is just above this; everything below is game code
HDR = re.compile(r'^// ([0-9a-f]{8})  (\S+)$')
CALL = re.compile(r'\b([A-Za-z_]\w*)\s*\(')
STR = re.compile(r'\bs_\w+_([0-9a-f]{8})\b')
SRCFILE = re.compile(r'\bs_(\w+?)_([ch])_[0-9a-f]{8}\b')
FILENAME = re.compile(r'\bs_(\w+?)_(bin|dat|thp|bmg|tpl|dbn|hps|ssm|ini)_[0-9a-f]{8}\b', re.I)

# callee name prefix -> subsystem hint (prefixes are library names already verified in symbols.txt)
HINTS = [('HSD_JObj', 'model'), ('HSD_DObj', 'model'), ('HSD_MObj', 'model'), ('HSD_TObj', 'model'),
         ('HSD_PObj', 'model'), ('HSD_AObj', 'anim'), ('HSD_FObj', 'anim'), ('HSD_CObj', 'camera'),
         ('HSD_LObj', 'light'), ('HSD_Fog', 'render'), ('HSD_State', 'render'), ('GX', 'render'),
         ('DVD', 'file-io'), ('CARD', 'memcard'), ('PAD', 'input'), ('THP', 'movie'), ('AX', 'audio'),
         ('VI', 'video'), ('OSReport', 'debug-print'), ('MTX', 'math'), ('PSMTX', 'math'), ('PSVEC', 'math'),
         ('sin', 'math'), ('cos', 'math'), ('atan', 'math'), ('sqrt', 'math'), ('OSAlloc', 'memory'),
         ('HSD_ObjAlloc', 'memory'), ('HSD_MemAlloc', 'memory'), ('memcpy', 'memory'), ('memset', 'memory')]


def parse(path):
    funcs, cur, buf = [], None, []
    for line in open(path, encoding='utf-8', errors='replace'):
        m = HDR.match(line.rstrip('\n'))
        if m:
            if cur: funcs.append((cur[0], cur[1], ''.join(buf)))
            cur, buf = (int(m.group(1), 16), m.group(2)), []
        elif cur:
            buf.append(line)
    if cur: funcs.append((cur[0], cur[1], ''.join(buf)))
    return funcs


def main():
    funcs = parse(os.path.join(G, 'decompiled', 'main_dol.c'))
    names = {n for _, n, _ in funcs}
    callees, callers = {}, collections.defaultdict(set)
    for a, n, body in funcs:
        cs = {c for c in CALL.findall(body) if c in names and c != n}
        callees[n] = cs
        for c in cs: callers[c].add(n)

    direct = {n: {h for c in callees[n] for p, h in HINTS if c.startswith(p)} for n in callees}
    rows, hint_count = [], collections.Counter()
    src_of = {}
    for a, n, body in funcs:
        # hints through up to 2 levels of unnamed callees ("~" marks an indirect hint)
        via = set()
        for c in callees[n]:
            if c.startswith('FUN_'):
                via |= direct[c]
                for c2 in callees[c]:
                    if c2.startswith('FUN_'): via |= direct[c2]
        hints = sorted(direct[n]) + sorted('~' + h for h in via - direct[n])
        srcs = sorted({f'{b}.{e}' for b, e in SRCFILE.findall(body)})
        fns = sorted({f'{b}.{e}' for b, e in FILENAME.findall(body)})
        strs = sorted(set(re.findall(r'\bs_\w+', body)))
        if a < GAME_END:
            cs = [x for x in srcs if x.endswith('.c')]
            if cs: src_of[a] = cs
            for h in hints: hint_count[h.lstrip('~')] += 1
        rows.append((a, n, body.count('\n'), len(callers[n]), len(callees[n]), hints, srcs, fns, strs))

    with open(os.path.join(G, 'symbols', 'game_map.tsv'), 'w', encoding='utf-8', newline='\r\n') as f:   # CRLF on every OS (checksummed)
        f.write('addr\tname\tlines\tcallers\tcallees\thints\tsource_files\tfile_names\tstrings\n')
        for a, n, ln, cr, ce, h, s, fn, st in rows:
            f.write(f'{a:08X}\t{n}\t{ln}\t{cr}\t{ce}\t{",".join(h)}\t{",".join(s)}\t{",".join(fn)}\t{",".join(st[:12])}\n')

    game = [r for r in rows if r[0] < GAME_END]
    unnamed = [r for r in game if r[1].startswith('FUN_')]
    md = ['# Game code map (generated by tools/game_map.py; behaviour notes, NOT names)', '',
          f'Functions below 0x{GAME_END:08X}: {len(game)} ({len(unnamed)} still `FUN_`). '
          f'All functions in the export: {len(rows)}.', '',
          '## Subsystem hints (game functions that reach a verified library function of that kind, directly or through up to 2 unnamed callees)', '',
          '| hint | functions |', '|---|---|']
    md += [f'| {h} | {c} |' for h, c in hint_count.most_common()]

    # runs of game functions between two functions that assert the same source file
    md += ['', '## Game source files (.c named in game-code asserts; a run is bounded by the first and last function citing it)', '',
           '| file | first | last | functions in run |', '|---|---|---|---|']
    by_file = collections.defaultdict(list)
    for a, ss in src_of.items():
        for s in ss: by_file[s].append(a)
    addrs = [r[0] for r in rows]
    for s, al in sorted(by_file.items(), key=lambda kv: min(kv[1])):
        lo, hi = min(al), max(al)
        inside = sum(1 for x in addrs if lo <= x <= hi)
        md.append(f'| {s} | {lo:08X} | {hi:08X} | {inside} ({len(al)} cite it) |')

    md += ['', '## Hubs: most-called unnamed game functions (name these first)', '',
           '| addr | callers | callees | lines | hints |', '|---|---|---|---|---|']
    for r in sorted(unnamed, key=lambda r: -r[3])[:60]:
        md.append(f'| {r[0]:08X} | {r[3]} | {r[4]} | {r[2]} | {",".join(r[5])} |')

    md += ['', '## Functions that reference disc file names', '', '| addr | name | files |', '|---|---|---|']
    for r in rows:
        if r[7]: md.append(f'| {r[0]:08X} | {r[1]} | {", ".join(r[7])} |')

    md += ['', '## Largest unnamed game functions', '', '| addr | lines | callers | hints |', '|---|---|---|---|']
    for r in sorted(unnamed, key=lambda r: -r[2])[:40]:
        md.append(f'| {r[0]:08X} | {r[2]} | {r[3]} | {",".join(r[5])} |')

    open(os.path.join(G, 'docs', 'game_map.md'), 'w', encoding='utf-8', newline='\r\n').write('\n'.join(md) + '\n')
    print(f'game_map: {len(rows)} functions, {len(game)} game, {len(unnamed)} unnamed game; '
          f'{len(by_file)} source files cited; wrote symbols/game_map.tsv, docs/game_map.md')


if __name__ == '__main__':
    main()
