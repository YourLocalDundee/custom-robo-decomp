"""Generate the relocation fixes in decomp/config/GXCE01/config.yml (dtk add_relocations / block_relocations).

Plan.md Phase 4 Milestone 2 (a shiftable build): every pointer in main.dol must be a relocation in dtk's split
objects, and nothing else may be one, so code and data can move. dtk finds almost all of them; this script finds
what it gets wrong, from evidence in main.dol's own bytes (tools/reloc_audit.py, method in its docstring), and writes
the fixes into config.yml between two marker lines, replacing the previous generated block. Nothing is edited by
hand; a rerun from fresh writes the same block.

  1. dtk's OWN relocations: config.yml without the generated block (and copies of symbols.txt / splits.txt, which
     dtk rewrites) is split again into decomp/build/relocs/ (`dtk dol split`, under a second) and linked with the
     project's mwld and ldscript into decomp/build/relocs/main.elf (its SHA-1 must be the retail one).
  2. tools/reloc_audit.py on that main.elf: code events and data words, classified:
       add   a code address dtk did not relocate (lis + addi / ori / load-store pair, small-data access): the
             high half gets `ha` (or `hi` before an ori), the low half `l`, a small-data access `sda21`; the target
             is the dtk symbol holding the address (+ addend);
       block a data word dtk relocated into the middle of a function that does not use it as a jump table (the
             function holding the target has no bctr, or never references the table), and a code address dtk
             relocated that the code uses as a number (an and / or / xor bit mask or a signed compare): its lis and
             every low half made from that lis.
  3. config.yml: the generated block (LF, dtk's own format), decomp/reports/relocs_report.txt (CRLF): every fix
     with its evidence, the statistics per pointer kind, the named pointer tables (symbols/cr_globals.txt) checked
     word by word, and the glue spans (constant-offset arithmetic from one dtk object into another).
  --check (batch 9, after the build): the audit of the built decomp/build/GXCE01/main.elf must find no miss, no
     false positive and no relocated value that differs from its target; the result is appended to the report.

Usage: python -I tools/gen_dtk_relocs.py [--check]
"""
import hashlib
import os
import re
import shutil
import subprocess
import sys
from collections import Counter

G = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(G, 'tools'))
import reloc_audit as ra  # noqa: E402

D = os.path.join(G, 'decomp')
CFG = os.path.join(D, 'config/GXCE01')
SCRATCH = os.path.join(D, 'build/relocs')
REPORT = os.path.join(D, 'reports/relocs_report.txt')
RETAIL = '6a73cd111ef349b20be294511b8c51a8addfb50b'
BEGIN = '# --- relocation fixes: generated by tools/gen_dtk_relocs.py from evidence (do not edit by hand) ---'
END = '# --- end of generated relocation fixes ---'
EXE = '.exe' if os.name == 'nt' else ''
DTK = os.path.join(G, 'tools/dtk', 'dtk' + EXE)


def run(cmd, cwd=D):
    p = subprocess.run(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    if p.returncode:
        sys.stdout.write(p.stdout.decode('utf-8', 'replace'))
        raise SystemExit(f'failed: {" ".join(map(str, cmd))}')
    return p.stdout


def mwld():
    """the project's linker command prefix (wibo on Linux / macOS, as configure.py does)"""
    ld = os.path.join(D, 'build/compilers/GC/1.3.2/mwldeppc.exe')
    wibo = os.path.join(D, 'build/tools/wibo')
    return ([wibo] if os.name != 'nt' and os.path.exists(wibo) else []) + [ld]


def link(objects, ldscript, out_elf, out_dol):
    """link objects (in this order) with the project's mwld and flags, then dtk elf2dol; -> SHA-1 of the DOL"""
    rsp = out_elf + '.rsp'      # paths relative to decomp/ (the linker runs there, like ninja)
    with open(os.path.join(D, rsp), 'wb') as f: f.write(''.join(o + '\n' for o in objects).encode())
    run(mwld() + ['-fp', 'hardware', '-nodefaults', '-lcf', ldscript, '-o', out_elf, '@' + rsp])
    run([DTK, 'elf2dol', out_elf, out_dol])
    return hashlib.sha1(open(os.path.join(D, out_dol), 'rb').read()).hexdigest()


def strip_block(text):
    """config.yml text without the generated block, LF only (write_config restores the file's own line ending)"""
    text = text.replace('\r\n', '\n')
    if BEGIN in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        text = text[:a].rstrip('\n') + '\n' + text[b:].lstrip('\n')
    return text.rstrip('\n') + '\n'


def unfixed_build():
    """split + link with dtk's own relocations only -> path of main.elf"""
    if os.path.exists(SCRATCH): shutil.rmtree(SCRATCH)
    os.makedirs(SCRATCH)
    rel = os.path.relpath(SCRATCH, D).replace('\\', '/')
    for f in ('symbols.txt', 'splits.txt'): shutil.copyfile(os.path.join(CFG, f), os.path.join(SCRATCH, f))
    y = strip_block(open(os.path.join(CFG, 'config.yml'), 'rb').read().decode())
    y = re.sub(r'(?m)^symbols: .*$', f'symbols: {rel}/symbols.txt', y)
    y = re.sub(r'(?m)^splits: .*$', f'splits: {rel}/splits.txt', y)
    open(os.path.join(SCRATCH, 'config.yml'), 'wb').write(y.encode())
    run([DTK, 'dol', 'split', f'{rel}/config.yml', f'{rel}/out'])
    import json
    units = json.load(open(os.path.join(SCRATCH, 'out/config.json')))['units']
    sha = link([u['object'] for u in units], f'{rel}/out/ldscript.lcf', f'{rel}/main.elf', f'{rel}/main.dol')
    if sha != RETAIL: raise SystemExit(f'unfixed link SHA-1 {sha} is not retail')
    return os.path.join(SCRATCH, 'main.elf')


def dtk_symbols():
    """{name: count} and {address: name} of decomp/config/GXCE01/symbols.txt"""
    cnt, at = Counter(), {}
    for line in open(os.path.join(CFG, 'symbols.txt'), encoding='utf-8'):
        m = re.match(r'(\S+) = (\.\w+):0x([0-9A-Fa-f]+);', line)
        if m: cnt[m[1]] += 1; at.setdefault(int(m[3], 16), m[1])
    return cnt, at


def target_spec(elf, objs, v, names):
    """dtk's target syntax for address v: the dtk symbol holding it + addend"""
    o = objs.containing(v)
    if o is None: raise SystemExit(f'no dtk symbol holds 0x{v:08X}')
    n = o[2] if names[o[2]] == 1 else f'{o[2]}!{elf.section_of(o[0])}:0x{o[0]:08X}'
    return n, v - o[0]


def fixes(elf, objs, c):
    """-> (adds [(section, site, type, target, addend, evidence)], blocks [(section, site, evidence)])"""
    names, _ = dtk_symbols()
    adds, blocks = [], []
    w = elf.word
    for k, a, v, d in c['misses']:
        n, add = target_spec(elf, objs, v, names)
        ev = f'{k} in {d["func"]}: value 0x{v:08X} = {n}+0x{add:X}'
        if k in ('MAT', 'EA') and d.get('hi') is not None:
            lo_is_ori = (w(a) >> 26) == 24
            if not d.get('reloc_hi'):
                adds.append((elf.section_of(d['hi']), d['hi'], 'hi' if lo_is_ori else 'ha', n, add,
                             f'{ev}; high half (lis) at 0x{d["hi"]:08X}'))
            if not d.get('reloc_lo', d.get('reloc')):
                adds.append((elf.section_of(a), a, 'l', n, add, f'{ev}; low half'))
        elif k in ('EA', 'SDAADDR'):
            adds.append((elf.section_of(a), a, 'sda21', n, add, f'{ev}; small-data access'))
        else:
            raise SystemExit(f'cannot fix {k} at 0x{a:08X}')
    for o, f, lst, why in c['fp_data']:
        for a, r in lst:
            blocks.append((elf.section_of(a), a, f'data word 0x{w(a):08X} in {o[2] if o else "?"} relocated by dtk '
                                                 f'to {r[2]}+0x{r[3]:X} (mid-function): {why}'))
    for hi, e in sorted(c['fp_code'].items()):
        uses = ', '.join(f'{k} at 0x{a:08X}' for k, a, v in sorted(e['uses']))
        blocks.append((elf.section_of(hi), hi, f'lis of 0x{(w(hi) & 0xffff) << 16:08X} in {e["func"]}: the value '
                                               f'is used as a number ({uses}), not as an address'))
        for a, v, t in sorted(e['lo']):
            blocks.append((elf.section_of(a), a, f'low half 0x{v:08X} made from the lis at 0x{hi:08X}'))
    adds.sort(key=lambda x: x[1])
    blocks.sort(key=lambda x: x[1])
    return adds, blocks


def write_config(adds, blocks):
    p = os.path.join(CFG, 'config.yml')
    raw = open(p, 'rb').read().decode()
    eol = '\r\n' if '\r\n' in raw else '\n'      # keep the file's own line ending (config.yml is CRLF in git)
    y = strip_block(raw)
    out = [BEGIN, '# Evidence per entry: decomp/reports/relocs_report.txt. Rerun: tools/batches/batch9_decomp_build.ps1.']
    if blocks:
        out.append('block_relocations:')
        for sec, a, ev in blocks: out.append(f'- source: {sec}:0x{a:08X}')
    if adds:
        out.append('add_relocations:')
        for sec, a, ty, n, add, ev in adds:
            out += [f'- source: {sec}:0x{a:08X}', f'  type: {ty}', f'  target: {n}']
            if add: out.append(f'  addend: 0x{add:X}')
    out.append(END)
    open(p, 'wb').write((y + '\n'.join(out) + '\n').replace('\n', eol).encode())


def tables(elf, objs):
    """the named pointer tables of symbols/cr_globals.txt in initialised data, word by word"""
    rows = []
    for line in open(os.path.join(G, 'symbols/cr_globals.txt'), encoding='utf-8'):
        m = re.match(r'(cr_g_\w+) = (\.\w+):0x([0-9A-Fa-f]+); // type:object datatype:([^ ]+)', line)
        if not m or m[2] not in ra.DATA: continue
        a = int(m[3], 16)
        n = re.search(r'\[(\d+)\]$', m[4])
        ptr = n and ('*' in m[4] or 'Func' in m[4])
        if ptr: end = a + 4 * int(n[1])
        else:
            o = objs.containing(a)
            end = o[1] if o else a + 4
        rel = sum(1 for x in range(a, end, 4) if elf.relocs.get(x, (0,))[0] == ra.R_ADDR32)
        null = sum(1 for x in range(a, end, 4) if elf.word(x) == 0)
        lo, hi = ra.moving_range(elf)
        raw = sum(1 for x in range(a, end, 4) if elf.relocs.get(x) is None and lo <= (elf.word(x) or 0) < hi)
        kind = f'{int(n[1])} pointers' if ptr else f'struct data to 0x{end:08X}'
        ok = raw == 0 and (not ptr or rel + null == int(n[1]))
        rows.append(f'  {"ok  " if ok else "FAIL"} 0x{a:08X} {m[1]} ({m[4]}, {kind}): {rel} relocated words, '
                    f'{null} NULL, {raw} unrelocated in-range words')
    return rows


def describe(elf, objs, c, raw, rels, adds, blocks):
    st = c['stats']
    mat_ok = st['RELMAT']
    lines = [
        'decomp/config/GXCE01/config.yml relocation fixes: generated by tools/gen_dtk_relocs.py (method: its docstring',
        'and tools/reloc_audit.py). Input: dtk\'s own relocations (config.yml without the generated block, split and',
        'linked in decomp/build/relocs/, SHA-1 retail).',
        '',
        f'relocations made by dtk: {len(elf.relocs)}; moving range 0x{ra.moving_range(elf)[0]:08X}-'
        f'0x{ra.moving_range(elf)[1] - 1:08X} (.init .. __ArenaLo)',
        f'functions analysed: {len(c["func_list"])}',
        'code (constant propagation, per pointer kind; "missed" = dtk made no relocation):',
        f'  lis + addi/ori address pairs: {mat_ok} relocated, {st["MAT"]} missed '
        f'({st["RELMAT split across blocks"]} relocated pairs have the lis in an earlier block)',
        f'  loads / stores at a lis address: {st["EA lis"]} ({sum(1 for k, a, v, d in c["misses"] if k == "EA" and d["base"] == "lis")} missed)',
        f'  small-data accesses (r13 / r2 + offset): {st["EA sda"]} '
        f'({sum(1 for k, a, v, d in c["misses"] if k == "EA" and d["base"] == "sda")} missed)',
        f'  small-data addresses (addi rD, r13 / r2, offset): {st["SDAADDR"]} '
        f'({sum(1 for k, a, v, d in c["misses"] if k == "SDAADDR")} missed)',
        f'  relocated addresses used as numbers (bit mask / signed compare): {st["LOGIC"] + st["SCMP"]} uses, '
        f'{len(c["fp_code"])} lis',
        f'data: {len(rels)} relocated words; unrelocated words in the moving range: {len(raw)}',
        f'  relocated into the middle of a function: {sum(len(x[2]) for x in c["jumptables"] + c["fp_data"])} words in '
        f'{len(c["jumptables"]) + len(c["fp_data"])} tables; jump tables (the function holding the targets has a '
        f'bctr and references the table): {len(c["jumptables"])} '
        f'({sum(1 for o, f, l, w in c["jumptables"] if o and not o[2].startswith("jumptable_"))} not named jumptable_ '
        f'by dtk); not a jump table: {len(c["fp_data"])}',
        f'glue (constant-offset arithmetic from one dtk object into another): {st["CROSS"]} accesses, '
        f'{len(c["glue"])} spans; padding must not be inserted inside a span',
        '',
        f'fixes written: add_relocations {len(adds)}, block_relocations {len(blocks)}',
    ]
    for sec, a, ty, n, add, ev in adds:
        lines.append(f'  add   {sec}:0x{a:08X} {ty} {n}{f"+0x{add:X}" if add else ""}  // {ev}')
    for sec, a, ev in blocks:
        lines.append(f'  block {sec}:0x{a:08X}  // {ev}')
    lines += ['', 'jump tables dtk did not name (verified):']
    for o, f, lst, why in c['jumptables']:
        if o and not o[2].startswith('jumptable_'):
            lines.append(f'  0x{o[0]:08X} {o[2]}: {len(lst)} cases in {f[2]}')
    lines += ['', 'named pointer tables (symbols/cr_globals.txt), words in their extent:'] + tables(elf, objs)
    lines += ['', 'glue spans (start .. end, section, the dtk objects at both ends):']
    for lo, hi in c['glue']:
        lines.append(f'  0x{lo:08X}..0x{hi:08X} {elf.section_of(lo)} {objs.containing(lo)[2]} .. '
                     f'{objs.containing(hi)[2]}')
    return lines


def blocked_sites():
    """source addresses of the generated block_relocations in config.yml"""
    y = open(os.path.join(CFG, 'config.yml'), 'rb').read().decode()
    if BEGIN not in y: return set()
    blk = y[y.index(BEGIN):y.index(END)]
    blk = blk[blk.find('block_relocations:'):].split('add_relocations:')[0] if 'block_relocations:' in blk else ''
    return {int(m, 16) for m in re.findall(r'- source: \.\w+:0x([0-9A-Fa-f]+)', blk)}


def check():
    elf, objs, rng, events, raw, rels = ra.audit(os.path.join(D, 'build/GXCE01/main.elf'))
    c = ra.classify(elf, objs, events, rels)
    bad = ra.consistency(elf, events, rels)
    blocked = blocked_sites()
    # the blocked sites are numbers on purpose: they show up as unrelocated in-range values, which is what we want
    misses = [e for e in c['misses'] if e[1] not in blocked and e[3].get('hi') not in blocked]
    raw_left = [x for x in raw if x[0] not in blocked]
    n = (len(misses), len(raw_left), len(c['fp_data']), len(c['fp_code']), len(bad))
    ok = not any(n)
    lines = ['', 'check of the built decomp/build/GXCE01/main.elf (batch 9, with the fixes):',
             f'  relocations {len(elf.relocs)}; code misses {n[0]}, unrelocated in-range data words {n[1]}, data false '
             f'positives {n[2]}, code false positives {n[3]}, relocated values different from their target {n[4]}; '
             f'left unrelocated on purpose (blocked): {len(c["misses"]) - n[0]} code, {len(raw) - n[1]} data',
             f'  result: {"OK" if ok else "FAIL"}']
    old = open(REPORT, 'rb').read().decode()
    cut = old.find('\r\n\r\ncheck of the built')     # rerunnable: replace an earlier check section
    old = old if cut < 0 else old[:cut + 2]
    with open(REPORT, 'wb') as f: f.write((old + ''.join(x + '\r\n' for x in lines)).encode())
    print(lines[2].strip()); print(lines[3].strip())
    return 0 if ok else 1


def main(argv):
    if '--check' in argv: return check()
    path = unfixed_build()
    elf, objs, rng, events, raw, rels = ra.audit(path)
    c = ra.classify(elf, objs, events, rels)
    c['func_list'] = ra.Code(elf, objs, *rng).funcs
    adds, blocks = fixes(elf, objs, c)
    if raw: raise SystemExit(f'{len(raw)} unrelocated in-range data words: classify them before fixing (none so far)')
    write_config(adds, blocks)
    lines = describe(elf, objs, c, raw, rels, adds, blocks)
    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, 'wb') as f: f.write(''.join(x + '\r\n' for x in lines).encode())
    print(f'gen_dtk_relocs: add {len(adds)}, block {len(blocks)} -> config.yml; report decomp/reports/relocs_report.txt')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
