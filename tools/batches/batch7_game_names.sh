#!/usr/bin/env bash
# Batch 7: game-code naming, stage 1 - the REAL names the game itself contains (no invented names).
# batch7_game_names.ps1 for Linux / macOS: same matcher, same merge into symbols/descriptive.txt, byte for byte.
# Runs tools/match_game_names.py (evidence kinds G1 parallel name/function tables, G2 self-naming strings, G3 source-file
# module notes; method in its docstring) and merges its name lines into symbols/descriptive.txt, tagged "// game-real",
# right after the marker line below (appended at the end, with the marker, if the marker is missing).
# Rerunnable, output identical on every run: replaces its own "// game-real" lines, and the matcher reads only
# main.dol, the dtk analysis and the committed hand names (never the Ghidra export, index.db or the C), so it does not
# depend on a previous run or rebuild. A hand line with exactly the generated name at the same address is taken over by
# the generated block (reported). Never overwrites a different name: the matcher reports CONFLICT lines and the batch
# stops. Outputs: symbols/game_real.txt, symbols/game_unnamed_real.txt (leftovers), symbols/descriptive.txt.
# Does not rebuild Ghidra (run_all.sh does).
set -euo pipefail
b=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
g=$(dirname "$(dirname "$b")")
. "$g/tools/common.sh"
desc="$g/symbols/descriptive.txt"
out="$g/symbols/game_real.txt"
# the marker line is part of the committed file: the .ps1 name in it stays
marker='// ---- Game-real names (plan.md step 48): GENERATED by tools/batches/batch7_game_names.ps1 from symbols/game_real.txt - do not edit these lines by hand'

# 1. the matcher (it skips the "// game-real" lines itself, so it reads only our hand names; on a conflict nothing is written)
set +e
summary=$("$PY" -I "$g/tools/match_game_names.py")
rc=$?
set -e
[ -z "$summary" ] || printf '%s\n' "$summary" | sed 's/^/batch7: /'
[ "$rc" != 1 ] || die 'match_game_names.py: CONFLICT - a game name would replace a different existing name (see symbols/game_real.txt); nothing merged'
[ "$rc" = 0 ] || die 'match_game_names.py failed'

# 2.-4. generated lines in descriptive.txt format, replacing the previous generated block after the marker
"$PY" -I - "$desc" "$out" "$marker" <<'EOF'
import re, sys
desc, out, marker = sys.argv[1:4]
rx = re.compile(r'^0x([0-9A-F]{8}) = (cr_\w+) // game-real (G1|G2) (.*)$')
gen = []
for l in open(out, encoding='utf-8'):
    l = l.rstrip('\r\n')
    m = rx.match(l)
    if not m:
        continue
    addr, name, kind, ev = m.groups()
    if kind == 'G1':
        e = re.match(r'^names:0x([0-9A-F]{8})\[(\d+)\]@0x[0-9A-F]{8} funcs:0x([0-9A-F]{8})\[(\d+)\] "(.*)"$', ev)
        if not e:
            sys.exit('batch7: unreadable G1 evidence: ' + l)
        why = ('entry %s of the function table 0x%s; name %s is entry %s of the game\'s name table 0x%s, directly adjacent, same length'
               % (e.group(4), e.group(3), e.group(5), e.group(2), e.group(1)))
    else:
        why = 'the function prints a message naming itself'
    gen.append((addr, name, '%s = .text:0x%s; // type:function scope:global // why: %s // game-real %s %s' % (name, addr, why, kind, ev)))

# drop the previous generated lines; hand lines with the very same name and address are taken over by the new block
key = set('%s %s' % (n, a) for a, n, _ in gen)
taken = 0
lines = []
for l in open(desc, encoding='utf-8'):
    l = l.rstrip('\r\n')
    if '// game-real ' in l:
        continue
    m = re.match(r'^(\S+) = \.text:0x([0-9A-Fa-f]{8});', l)
    if m and ('%s %s' % (m.group(1), m.group(2).upper())) in key:
        taken += 1
        continue
    lines.append(l)
# insert after the marker and its "//      " continuation lines
if marker in lines:
    i = lines.index(marker)
else:
    lines += ['', marker]
    i = len(lines) - 1
j = i + 1
while j < len(lines) and lines[j].startswith('//      '):
    j += 1
new = lines[:j] + [t for _, _, t in gen] + lines[j:]
open(desc, 'w', encoding='utf-8', newline='\r\n').write(''.join(x + '\n' for x in new))
print('batch7: merged %d game-real names into symbols/descriptive.txt (%d identical hand lines taken over)' % (len(gen), taken))
EOF
