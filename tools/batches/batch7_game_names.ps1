#Requires -Version 7
# Batch 7: game-code naming, stage 1 - the REAL names the game itself contains (no invented names).
# Runs tools\match_game_names.py (evidence kinds G1 parallel name/function tables, G2 self-naming strings, G3 source-file
# module notes; method in its docstring) and merges its name lines into symbols\descriptive.txt, tagged "// game-real",
# right after the marker line below (appended at the end, with the marker, if the marker is missing).
# Why descriptive.txt and not a new file: the names are cr_ names for game code, which is what descriptive.txt holds;
# ApplySymbols.java, the lint, ParseHeaders.java (cr_ prototypes) and the cross-check already read it, and the tagged,
# regenerated lines follow batch 6's "lib-candidate" lines in symbols.txt. cr_globals.txt is not touched: the game gives no
# names to its tables, so naming them is stage 2.
# Rerunnable, output identical on every run: replaces its own "// game-real" lines, and the matcher reads only
# main.dol, the dtk analysis and the committed hand names (never the Ghidra export, index.db or the C), so it does not
# depend on a previous run or rebuild. A hand line with exactly the generated name at the same address is taken over by
# the generated block (reported). Never overwrites a different name: the matcher reports CONFLICT lines and the batch
# stops. Outputs: symbols\game_real.txt, symbols\game_unnamed_real.txt (leftovers), symbols\descriptive.txt.
# Does not rebuild Ghidra (run_all.ps1 does).
$ErrorActionPreference = 'Stop'
$g = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
$desc = "$g/symbols/descriptive.txt"
$out = "$g/symbols/game_real.txt"
$marker = '// ---- Game-real names (plan.md step 48): GENERATED by tools/batches/batch7_game_names.ps1 from symbols/game_real.txt - do not edit these lines by hand'

# 1. the matcher (it skips the "// game-real" lines itself, so it reads only our hand names; on a conflict nothing is written)
$summary = python -I "$g/tools/match_game_names.py"
$rc = $LASTEXITCODE
$summary | ForEach-Object { "batch7: $_" }
if ($rc -eq 1) { throw 'match_game_names.py: CONFLICT - a game name would replace a different existing name (see symbols\game_real.txt); nothing merged' }
if ($rc) { throw 'match_game_names.py failed' }

# 2. generated lines in descriptive.txt format
$rx = '^0x([0-9A-F]{8}) = (cr_\w+) // game-real (G1|G2) (.*)$'
$gen = foreach ($l in Get-Content -LiteralPath $out) {
    $m = [regex]::Match($l, $rx)
    if (-not $m.Success) { continue }
    $addr, $name, $kind, $ev = $m.Groups[1].Value, $m.Groups[2].Value, $m.Groups[3].Value, $m.Groups[4].Value
    if ($kind -eq 'G1') {
        $e = [regex]::Match($ev, '^names:0x([0-9A-F]{8})\[(\d+)\]@0x[0-9A-F]{8} funcs:0x([0-9A-F]{8})\[(\d+)\] "(.*)"$')
        if (-not $e.Success) { throw "batch7: unreadable G1 evidence: $l" }
        $why = "entry $($e.Groups[4].Value) of the function table 0x$($e.Groups[3].Value); name $($e.Groups[5].Value) is entry " +
            "$($e.Groups[2].Value) of the game's name table 0x$($e.Groups[1].Value), directly adjacent, same length"
    } else {
        $why = 'the function prints a message naming itself'
    }
    [pscustomobject]@{ Addr = $addr; Name = $name; Line = "$name = .text:0x$addr; // type:function scope:global // why: $why // game-real $kind $ev" }
}
$gen = @($gen)

# 3. drop the previous generated lines; hand lines with the very same name and address are taken over by the new block
$key = @{}
foreach ($x in $gen) { $key["$($x.Name) $($x.Addr)"] = 1 }
$taken = 0
$lines = @(Get-Content -LiteralPath $desc | Where-Object { $_ -notmatch '// game-real ' } | Where-Object {
    $m = [regex]::Match($_, '^(\S+) = \.text:0x([0-9A-Fa-f]{8});')
    if ($m.Success -and $key.ContainsKey("$($m.Groups[1].Value) $($m.Groups[2].Value.ToUpper())")) { $script:taken++; $false } else { $true }
})

# 4. insert after the marker and its "//      " continuation lines
$i = [array]::IndexOf($lines, $marker)
if ($i -lt 0) { $lines += @('', $marker); $i = $lines.Count - 1 }
$j = $i + 1
while ($j -lt $lines.Count -and $lines[$j].StartsWith('//      ')) { $j++ }
$new = @($lines[0..($j - 1)]) + @($gen | ForEach-Object Line) + $(if ($j -lt $lines.Count) { @($lines[$j..($lines.Count - 1)]) } else { @() })
Set-Content -LiteralPath $desc -Value $new
"batch7: merged $($gen.Count) game-real names into symbols\descriptive.txt ($taken identical hand lines taken over)"
